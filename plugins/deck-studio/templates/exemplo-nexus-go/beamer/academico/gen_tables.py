"""Write tables.tex from data/thesis_tables.json: no table number is typed by hand.

Run: python -I -X utf8 beamer/academico/gen_tables.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE.parents[1] / "data" / "thesis_tables.json").read_text(encoding="utf8"))


def f2(x):
    return f"{x:.2f}" if isinstance(x, (int, float)) else str(x)


def math(s):
    """Header cells come as raw TeX; wrap the ones with math in $...$."""
    return f"${s}$" if ("_" in s or "^" in s or "\\" in s) and "$" not in s and "multicolumn" not in s else s


def best(rows, cols, low=()):
    """Set of (row, col) holding the best numeric value of each column (every row of a tie, as in the thesis)."""
    out = set()
    for c in cols:
        vals = [(r[c], i) for i, r in enumerate(rows) if isinstance(r[c], (int, float))]
        if vals:
            m = (min if c in low else max)(v for v, _ in vals)
            out |= {(i, c) for v, i in vals if v == m}
    return out


def tabular(rows, spec, cols, low=(), fmt=f2, rule_after=()):
    b = best(rows, cols, low)
    lines = []
    for i, r in enumerate(rows):
        cells = [fmt(v) if j in cols else str(v).replace(r"(\gamma)", r"($\gamma$)") for j, v in enumerate(r)]
        cells = [f"\\textbf{{{c}}}" if (i, j) in b else c for j, c in enumerate(cells)]
        lines.append(" & ".join(cells) + r" \\" + (r" \midrule" if i in rule_after else ""))
    return f"\\begin{{tabular}}{{{spec}}}\\toprule\n" + "\n".join(lines) + "\n\\bottomrule\\end{tabular}"


def head(rows):
    return " & ".join(math(h) for h in rows[0]) + r" \\ \midrule"


def block(name, key, spec, cols, low=(), fmt=f2, rule_after=()):
    rows = T[key]["rows"]
    body = tabular(rows[1:], spec, cols, low, fmt, rule_after)
    body = body.replace(r"\toprule", r"\toprule" + "\n" + head(rows), 1)
    return f"% {T[key]['label']}\n\\newcommand{{\\{name}}}{{%\n{body}}}\n"


def thousands(x):
    return f"{int(x):,}" if isinstance(x, float) else str(x)


out = ["% generated by gen_tables.py from data/thesis_tables.json; do not edit\n"]
out.append(block("TabCorpus", "corpus", "lrrrr", {1, 2, 3, 4}, fmt=thousands).replace(r"\textbf", ""))
out.append(block("TabGNN", "gnn", "llrrrr", {2, 3, 4, 5}))
out.append(block("TabLate", "late", "lrrrr", {1, 2, 3, 4}))
out.append(block("TabVV", "vector_vs_vision", "llrrrr", {2, 3, 4, 5}).replace(r"\textbf", ""))
for o in ("BP", "CC", "MF"):
    out.append(block(f"TabTest{o}", f"test_{o}", "lrrrrrr", {1, 2, 3, 4, 5, 6}, low={6}, rule_after={5, 7}))
cost = [[int(v) if isinstance(v, float) and v.is_integer() and j in (1, 6) else v for j, v in enumerate(r)]
        for r in T["cost"]["rows"][:-1]]  # drop the Total row
T["cost_main"] = {"label": "tab:custo", "rows": cost}
out.append(block("TabCost", "cost_main", "lrrrrrr", {2, 3, 5}, low={2, 3, 5},
                 fmt=lambda v: f"{v:g}" if isinstance(v, float) else str(v)))
gain = T["graph_gain_by_degree"]["rows"]
out.append("% " + T["graph_gain_by_degree"]["label"] + "\n\\newcommand{\\TabGain}{%\n\\begin{tabular}{lrrr}\\toprule\n"
           + " & ".join(gain[0]) + r" \\ \midrule" + "\n"
           + "\n".join(" & ".join(c.replace(">=", r"$\geq$").replace("-0", "$-$0") for c in r) + r" \\" for r in gain[1:])
           + "\n\\bottomrule\\end{tabular}}\n")
cov = T["coverage"]["rows"]
out.append("% " + T["coverage"]["label"] + "\n\\newcommand{\\TabCov}{%\n\\begin{tabular}{lrrr}\\toprule\nMethod family & BP (\\%) & CC (\\%) & MF (\\%) \\\\ \\midrule\n"
           + "\n".join(f"{r[0]} & {r[1]:.1f} & {r[3]:.1f} & {r[5]:.1f} \\\\" for r in cov[2:])
           + "\n\\bottomrule\\end{tabular}}\n")

(HERE / "tables.tex").write_text("\n".join(out), encoding="utf8")

# self-check: the headline numbers quoted in the slide text match the JSON
late = {r[0]: r for r in T["late"]["rows"]}
assert late["Linear interpolation (\\gamma)"][4] == 67.06
assert T["test_BP"]["rows"][-1][3] == 58.69 and T["test_BP"]["rows"][2][3] == 48.92  # +9.77
print("tables.tex written", file=sys.stderr)
