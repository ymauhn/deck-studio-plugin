"""Write gains.tex (the bars of the "Where the gains come from" chart) from data/thesis_tables.json:
no chart number is typed by hand.

Run from the kit root: python -I -X utf8 beamer/v2-colegas/gen_gains.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
T = json.loads((HERE.parents[1] / "data" / "thesis_tables.json").read_text(encoding="utf8"))


def avg(key, match):
    """AVG column of the first row of table `key` whose leading cells equal `match`."""
    rows = T[key]["rows"]
    for row in rows[1:]:
        if list(row[:len(match)]) == match:
            return row[rows[0].index("AVG")]
    raise KeyError(f"{key}: no row {match}")


# (label, value, colour): mean validation wFmax of each stage, in the order of the funnel
bars = [
    ("Naive", avg("naive", ["Naive (term frequency)"]), "gray"),
    ("Gen.~1", avg("vector_vs_vision", ["First Generation", "Vector"]), "net"),
    ("ProtT5 alone", avg("hops_vector", [0.0]), "seq"),
    ("Fixed", avg("vector_vs_vision", ["Fixed propagation", "Vector"]), "net"),
    ("Early", avg("vector_vs_vision", ["Early fusion", "Vector"]), "fus"),
    ("Late", avg("late", ["Linear interpolation (\\gamma)"]), "fus"),
]
items = ", ".join(f"{i}/{v:.2f}/{c}/{label}" for i, (label, v, c) in enumerate(bars, 1))
(HERE / "gains.tex").write_text(
    "% generated by gen_gains.py from data/thesis_tables.json; do not edit\n"
    f"\\newcommand{{\\GainBars}}{{{items}}}\n", encoding="utf8")
print(items)
