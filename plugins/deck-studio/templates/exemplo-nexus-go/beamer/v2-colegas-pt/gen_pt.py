# cells that stay as they are: names, acronyms and math headers
KEEP = {"BP", "CC", "MF", "AuPRC", "IAuPRC", "VRAM (GiB)", "DeepGraphGO", "SEGT-GO", "Mashup", "MELISSA", "deepNF",
        "NEXUS-GO/Fixed", "NEXUS-GO/GNN", "NEXUS-GO/Early", "NEXUS-GO/Late", r"BP (\%)", r"CC (\%)", r"MF (\%)",
        "DeepGraphGO / SEGT-GO", "Mashup / MELISSA / deepNF"}
# bar labels of the gains chart; the route names Fixed, Early and Late stay as they are
BARS = {"Naive": "Ingênuo", "Gen.~1": "Ger.~1", "ProtT5 alone": "Só ProtT5", "Fixed": "Fixed", "Early": "Early",
        "Late": "Late"}
used = set()


def num(s):
    """Brazilian number format: 73,768 -> 73.768 and 55.78 -> 55,78."""
    s = re.sub(r"(\d),(\d{3})(?!\d)", "\\1\0\\2", s)
    return re.sub(r"(\d)\.(\d)", r"\1,\2", s).replace("\0", ".")


def cell(c):
    key = c.strip()
    if key in CELLS:
        used.add(key)
        return c.replace(key, CELLS[key])
    # a new English label in the tables must not reach the Portuguese deck untranslated
    words = re.sub(r"\$[^$]*\$|\\textbf|\[[fgh]\]", "", key)
    assert key in KEEP or not re.search(r"[A-Za-z]", words), f"no Portuguese label for the table cell {key!r}"
    return num(c)


def row(line):
    if " & " not in line:
        return line
    body, sep, tail = line.partition(r" \\")
    return " & ".join(cell(c) for c in body.split(" & ")) + sep + tail


src = (EN / "tables.tex").read_text(encoding="utf8").splitlines()
head = "% generated by gen_pt.py from ../v2-colegas/tables.tex (gen_tables.py, data/thesis_tables.json); do not edit"
assert src[0].startswith("% generated by gen_tables.py"), src[0]
tables = "\n".join([head] + [row(line) for line in src[1:]]) + "\n"
# advisor (04/11): best result of the heads table in bold; the English generator braces those cells
vv = re.search(r"\\newcommand\{\\TabVV\}.*?\\end\{tabular\}", tables, re.S)
tables = tables[:vv.start()] + re.sub(r"\{(\d+,\d+)\}", r"\\textbf{\1}", vv.group(0)) + tables[vv.end():]
assert r"\textbf{56,52}" in tables
assert used == set(CELLS), f"cells not found in the English tables: {set(CELLS) - used}"

# \GainBars items i/value/colour/label become i/value/colour/label/value with a decimal comma (the value
# stays a TikZ coordinate; the comma is braced so that \foreach does not split on it)
items = re.search(r"\\GainBars\}\{(.*)\}", (EN / "gains.tex").read_text(encoding="utf8")).group(1).split(", ")
bars = []
for item in items:
    i, v, c, label = item.split("/")
    assert label in BARS, f"no Portuguese label for the bar {label!r}"
    bars.append(f"{i}/{v}/{c}/{BARS[label]}/{v.replace('.', '{,}')}")
assert len(bars) == len(BARS), bars
# advisor (04/11): the learned GNN alone, read from the generated heads table, between Só ProtT5 and Fixed
gnn = re.search(r"GNN de ponta a ponta & Vetorial & [^&]+& [^&]+& [^&]+& ([\d,]+)", tables).group(1)
bars = [b if int(b.split("/")[0]) < 4 else f"{int(b.split('/')[0]) + 1}/{b.split('/', 1)[1]}" for b in bars]
bars.insert(3, f"4/{gnn.replace(',', '.')}/net/GNN/{gnn.replace(',', '{,}')}")
gains = ("% generated by gen_pt.py from ../v2-colegas/gains.tex (gen_gains.py, data/thesis_tables.json); do not edit\n"
         f"\\newcommand{{\\GainBars}}{{{', '.join(bars)}}}\n")

# self-check: no English number format is left, and the headline numbers came through
assert all(re.fullmatch(r"\d{1,3}(\.\d{3})+", n) for n in re.findall(r"\d+\.\d+", tables))
assert r"\textbf{67,06}" in tables and "73.768" in tables and "6/65.84/fus/Early/65{,}84" in gains and "4/63.32/net/GNN/63{,}32" in gains
(HERE / "tables.tex").write_text(tables, encoding="utf8")
(HERE / "gains.tex").write_text(gains, encoding="utf8")
print(gains.splitlines()[1])
